// Adapted from AOSP DefaultVariants.kt, Copyright (C) 2022 The Android Open
// Source Project, Apache-2.0. Original source and notices are retained in
// test_data/default_variants; provenance is in docs/android-studio/ports/default-variants.json.
fn default_variant<'a>(
    variants: &'a [VariantDefinition],
    preferred_build_types: &BTreeSet<String>,
    preferred_product_flavors: &BTreeSet<String>,
) -> Option<&'a str> {
    let dimensions = variants
        .iter()
        .map(|variant| variant.product_flavors.len())
        .min()?;
    let compare_flavors = |left: &VariantDefinition, right: &VariantDefinition, preferred: bool| {
        left.product_flavors
            .iter()
            .zip(&right.product_flavors)
            .take(dimensions)
            .map(|(left, right)| {
                if preferred {
                    (!preferred_product_flavors.contains(left))
                        .cmp(&!preferred_product_flavors.contains(right))
                } else {
                    left.encode_utf16().cmp(right.encode_utf16())
                }
            })
            .find(|ordering| *ordering != Ordering::Equal)
            .unwrap_or(Ordering::Equal)
    };
    variants
        .iter()
        .reduce(|left, right| {
            let preferred_build_type = |variant: &VariantDefinition| {
                variant
                    .build_type
                    .as_ref()
                    .is_some_and(|build_type| preferred_build_types.contains(build_type))
            };
            let ordering = (!preferred_build_type(left))
                .cmp(&!preferred_build_type(right))
                .then_with(|| compare_flavors(left, right, true))
                .then_with(|| {
                    (left.build_type.as_deref() != Some("debug"))
                        .cmp(&(right.build_type.as_deref() != Some("debug")))
                })
                .then_with(|| compare_flavors(left, right, false))
                .then_with(|| match (&left.build_type, &right.build_type) {
                    (Some(left), Some(right)) => left.encode_utf16().cmp(right.encode_utf16()),
                    _ => left.build_type.is_some().cmp(&right.build_type.is_some()),
                });
            if ordering == Ordering::Greater {
                right
            } else {
                left
            }
        })
        .map(|variant| variant.name.as_str())
}

impl ExportedModule {
    fn into_module(self) -> Result<Module> {
        let mut module = Module {
            path: self.path,
            directory: self.directory,
            namespace: self.namespace,
            kind: self.kind,
            default_variant: self.default_variant,
            source_providers: self.source_providers,
            evaluated_providers: self.evaluated_providers,
            variants: self.variants,
        };
        if let Some(selection) = self.default_variant_selection {
            ensure!(
                module
                    .variants
                    .iter()
                    .map(|variant| &variant.name)
                    .eq(selection.variants.iter().map(|variant| &variant.name)),
                "Default variant metadata does not match Android module {}",
                module.path
            );
            module.default_variant = if selection.multiplatform {
                selection
                    .variants
                    .first()
                    .map(|variant| variant.name.clone())
            } else {
                default_variant(
                    &selection.variants,
                    &selection.preferred_build_types,
                    &selection.preferred_product_flavors,
                )
                .map(str::to_owned)
            };
        }
        Ok(module)
    }
}

#[derive(Clone, Debug)]
pub struct SelectedProject {
    pub model: Arc<ProjectModel>,
    pub selected: VariantId,
    pub variants: BTreeMap<String, String>,
}

impl ProjectModel {
    pub fn library_variants(&self) -> Vec<VariantId> {
        let mut variants = self
            .modules
            .iter()
            .filter(|module| module.kind == ModuleKind::Library)
            .flat_map(|module| {
                module.variants.iter().map(move |variant| VariantId {
                    module: module.path.clone(),
                    variant: variant.name.clone(),
                })
            })
            .collect::<Vec<_>>();
        variants.sort();
        variants
    }

    pub fn default_library_variant(&self) -> Option<VariantId> {
        self.modules
            .iter()
            .filter(|module| module.kind == ModuleKind::Library)
            .flat_map(|module| module.variants.iter().map(move |variant| (module, variant)))
            .min_by_key(|(module, variant)| {
                (
                    &module.path,
                    module.default_variant.as_ref() != Some(&variant.name),
                    !(variant.name == "debug" || variant.name.ends_with("Debug")),
                    &variant.name,
                )
            })
            .map(|(module, variant)| VariantId {
                module: module.path.clone(),
                variant: variant.name.clone(),
            })
    }

    pub fn default_target(&self) -> Option<AndroidTarget> {
        self.modules
            .iter()
            .filter(|module| module.kind == ModuleKind::Application)
            .filter_map(|module| {
                let default = module.default_variant.as_ref()?;
                let variant = module
                    .variants
                    .iter()
                    .find(|variant| &variant.name == default)?;
                Some((module, variant, variant.output_listing.as_ref()?))
            })
            .min_by_key(|(module, _, _)| &module.path)
            .map(|(module, variant, output_listing)| AndroidTarget {
                module: module.path.clone(),
                variant: variant.name.clone(),
                output_listing: output_listing.clone(),
            })
    }

    pub fn targets(&self) -> Vec<AndroidTarget> {
        let mut targets = self
            .modules
            .iter()
            .filter(|module| module.kind == ModuleKind::Application)
            .flat_map(|module| {
                module.variants.iter().filter_map(|variant| {
                    Some(AndroidTarget {
                        module: module.path.clone(),
                        variant: variant.name.clone(),
                        output_listing: variant.output_listing.clone()?,
                    })
                })
            })
            .collect::<Vec<_>>();
        targets.sort_by(|left, right| {
            (&left.module, &left.variant).cmp(&(&right.module, &right.variant))
        });
        targets
    }

    pub fn variant(&self, id: &VariantId) -> Option<(&Module, &Variant)> {
        let module = self
            .modules
            .iter()
            .find(|module| module.path == id.module)?;
        Some((
            module,
            module
                .variants
                .iter()
                .find(|variant| variant.name == id.variant)?,
        ))
    }

    pub fn select(self: &Arc<Self>, selected: VariantId) -> Result<SelectedProject> {
        let mut variants = BTreeMap::new();
        let mut pending = vec![selected.clone()];
        while let Some(id) = pending.pop() {
            if let Some(previous) = variants.insert(id.module.clone(), id.variant.clone()) {
                ensure!(
                    previous == id.variant,
                    "The selected graph requires multiple variants of {} ({previous}, {}); one active variant cannot represent it",
                    id.module,
                    id.variant
                );
                continue;
            }
            let (_, variant) = self.variant(&id).with_context(|| {
                format!(
                    "Android variant {} in {} is unavailable; sync again",
                    id.variant, id.module
                )
            })?;
            for component in &variant.components {
                for dependency in &component.dependencies {
                    if let Dependency::Project { module, variant } = dependency {
                        pending.push(VariantId {
                            module: module.clone(),
                            variant: variant.clone(),
                        });
                    }
                }
            }
        }
        Ok(SelectedProject {
            model: self.clone(),
            selected,
            variants,
        })
    }
}

impl SelectedProject {
    /// Modules visible to a source component. Test-only edges do not enter a main source scope.
    pub fn visible_modules(&self, owner: &str, scope: SourceScope) -> BTreeSet<String> {
        let mut visible = BTreeSet::new();
        let mut pending = vec![owner.to_owned()];
        while let Some(path) = pending.pop() {
            if !visible.insert(path.clone()) {
                continue;
            }
            let Some((module, variant)) = self.modules().find(|(module, _)| module.path == path)
            else {
                continue;
            };
            for component in &variant.components {
                if component.scope != SourceScope::Main
                    && !(path == owner && component.scope == scope)
                {
                    continue;
                }
                pending.extend(component.dependencies.iter().filter_map(|dependency| {
                    if let Dependency::Project {
                        module: dependency, ..
                    } = dependency
                    {
                        // Features belong to the app package but are not visible to base app sources.
                        let packaged_feature = module.kind == ModuleKind::Application
                            && self.modules().any(|(candidate, _)| {
                                candidate.path == *dependency
                                    && candidate.kind == ModuleKind::DynamicFeature
                            });
                        (!packaged_feature).then(|| dependency.clone())
                    } else {
                        None
                    }
                }));
            }
        }
        visible
    }

    pub fn modules(&self) -> impl Iterator<Item = (&Module, &Variant)> {
        self.variants.iter().filter_map(|(module, variant)| {
            self.model.variant(&VariantId {
                module: module.clone(),
                variant: variant.clone(),
            })
        })
    }

    pub fn projection(&self) -> serde_json::Value {
        serde_json::Value::Array(self.modules().map(|(module, variant)| serde_json::json!({
            "project": module.path, "variant": variant.name, "directory": module.directory,
            "kind": module.kind, "components": variant.components,
        })).collect())
    }

    pub fn kotlin_variants(&self) -> String {
        self.variants
            .iter()
            .filter(|(module, _)| {
                self.model.modules.iter().any(|candidate| {
                    candidate.path == **module && candidate.kind != ModuleKind::Jvm
                })
            })
            .map(|(module, variant)| format!("{module}={variant}"))
            .collect::<Vec<_>>()
            .join(";")
    }

    pub fn validate_target(&self, target: &AndroidTarget) -> Result<()> {
        ensure!(
            self.selected == VariantId::from(target) && self.model.targets().contains(target),
            "The Android target does not belong to the current project model"
        );
        Ok(())
    }
}

