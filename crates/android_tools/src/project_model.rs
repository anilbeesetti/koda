#[derive(Clone, Default)]
pub struct ModelState {
    generation: u64,
    root: Option<PathBuf>,
    pub model: Option<Arc<ProjectModel>>,
    pub selected: Option<Arc<SelectedProject>>,
    model_revision: Option<u64>,
    evaluated_inputs: Option<Arc<crate::evaluated_tree_inputs::EvaluatedTreeInputs>>,
}

impl ModelState {
    pub fn model_revision(&self) -> Option<u64> {
        self.model_revision
    }

    pub fn evaluated_inputs(
        &self,
    ) -> Option<&Arc<crate::evaluated_tree_inputs::EvaluatedTreeInputs>> {
        self.evaluated_inputs.as_ref()
    }

    pub fn root(&self) -> Option<&Path> {
        self.root.as_deref()
    }

    pub fn token(&self) -> ModelToken {
        ModelToken {
            generation: self.generation,
            root: self.root.clone(),
        }
    }
    pub fn is_current(&self, token: &ModelToken) -> bool {
        self.token() == *token
    }
    pub fn invalidate(&mut self, root: Option<PathBuf>) -> ModelToken {
        self.generation = self.generation.wrapping_add(1);
        self.root = root;
        self.model = None;
        self.selected = None;
        self.model_revision = None;
        self.evaluated_inputs = None;
        self.token()
    }
    pub fn publish(&mut self, token: &ModelToken, model: ProjectModel) -> Result<()> {
        ensure!(
            self.is_current(token)
                && self.root.as_ref().is_some_and(|root| root == &model.root
                    || root.canonicalize().is_ok_and(|root| root == model.root)),
            "Discarded an outdated Android sync result"
        );
        self.model = Some(Arc::new(model));
        self.model_revision = Some(token.revision());
        self.evaluated_inputs = None;
        Ok(())
    }

    pub fn publish_evaluated(
        &mut self,
        token: &ModelToken,
        capture: crate::evaluated_tree_inputs::EvaluatedTreeInputs,
    ) -> Result<()> {
        ensure!(
            self.is_current(token)
                && capture.token() == token
                && self
                    .root
                    .as_ref()
                    .is_some_and(|root| root == &capture.model().root
                        || root
                            .canonicalize()
                            .is_ok_and(|root| root == capture.model().root)),
            "Discarded an outdated evaluated Android sync result"
        );
        self.model = Some(capture.model().clone());
        self.selected = None;
        self.model_revision = Some(token.revision());
        self.evaluated_inputs = Some(Arc::new(capture));
        Ok(())
    }
    pub fn select(&mut self, id: Option<VariantId>) -> Result<()> {
        self.generation = self.generation.wrapping_add(1);
        self.selected = None;
        if let Some(id) = id {
            self.selected = Some(Arc::new(
                self.model
                    .as_ref()
                    .context("Sync the Android project first")?
                    .select(id)?,
            ));
        }
        Ok(())
    }
}

fn valid_module(name: &str) -> bool {
    name == ":"
        || (name.starts_with(':')
            && name[1..].split(':').all(|part| {
                !part.is_empty()
                    && part.chars().all(|character| {
                        character.is_ascii_alphanumeric() || "_-.$".contains(character)
                    })
            }))
}
fn valid_variant(name: &str) -> bool {
    !name.is_empty()
        && name
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || "_-".contains(character))
}

/// Evaluated directory provenance captured from one current, trusted Gradle root.
///
/// This immutable value cannot detect later store changes by itself. Callers must
/// check `is_current` before dispatch and before applying a parsed model.
#[derive(Clone)]
pub struct EvaluatedModelPaths {
    root: PathBuf,
    token: crate::project_context::RootToken,
    modules: BTreeMap<String, PathBuf>,
}

impl EvaluatedModelPaths {
    pub fn capture(
        store: &crate::project_context::ContextStore,
        token: &crate::project_context::RootToken,
        root: &Path,
    ) -> Result<Self> {
        use crate::project_context::{ModuleOwner, ObservationPhase};
        ensure!(
            store.is_current(token),
            "Evaluated model paths require a current trusted root"
        );
        let handle = store
            .handles()
            .find(|handle| store.token(*handle).as_ref() == Some(token))
            .context("Evaluated model root was removed")?;
        let snapshot = store
            .snapshot(handle)
            .context("Import the evaluated project context first")?;
        ensure!(
            store.root_path(handle) == Some(root)
                && snapshot.root() == root
                && snapshot.phase() == ObservationPhase::Complete,
            "Evaluated model paths belong to an incomplete or different root"
        );
        let mut modules = BTreeMap::new();
        for module in snapshot.modules() {
            ensure!(
                matches!(snapshot.module_owner(module.directory()), ModuleOwner::Module(owner) if owner == module.path()),
                "Evaluated module {} has ambiguous directory ownership",
                module.path()
            );
            modules.insert(module.path().to_owned(), module.directory().to_path_buf());
        }
        Ok(Self {
            root: root.to_path_buf(),
            token: token.clone(),
            modules,
        })
    }

    pub fn is_current(&self, store: &crate::project_context::ContextStore) -> bool {
        store.is_current(&self.token)
    }
}

pub fn parse_model(output: &str, root: &Path) -> Result<ProjectModel> {
    parse_model_with_paths(output, root, None)
}

/// Parse paths proven by evaluated Gradle module getters. The caller retains
/// responsibility for rejecting a result after the captured context expires.
pub fn parse_model_with_context(
    output: &str,
    root: &Path,
    paths: &EvaluatedModelPaths,
) -> Result<ProjectModel> {
    ensure!(
        paths.root == root,
        "Evaluated model paths belong to a different root"
    );
    parse_model_with_paths(output, root, Some(paths))
}

fn parse_model_with_paths(
    output: &str,
    root: &Path,
    paths: Option<&EvaluatedModelPaths>,
) -> Result<ProjectModel> {
    let mut records = output.lines().filter_map(|line| line.strip_prefix(OUTPUT));
    let exported: ExportedProjectModel = serde_json::from_str(
        records
            .next()
            .context("Gradle returned no Android project model")?,
    )?;
    ensure!(
        records.next().is_none(),
        "Gradle returned multiple Android project models"
    );
    let model = ProjectModel {
        version: exported.version,
        root: exported.root,
        modules: exported
            .modules
            .into_iter()
            .map(ExportedModule::into_module)
            .collect::<Result<_>>()?,
        diagnostics: exported.diagnostics,
    };
    ensure!(
        model.version == 1,
        "Unsupported Android project model version {}",
        model.version
    );
    let root = root.canonicalize()?;
    ensure!(
        model.root == root,
        "The Android model belongs to a different project"
    );
    let mut modules = BTreeSet::new();
    for module in &model.modules {
        ensure!(
            valid_module(&module.path) && modules.insert(&module.path),
            "Invalid or duplicate Android module {}",
            module.path
        );
        let boundary = if let Some(paths) = paths {
            let directory = paths
                .modules
                .get(&module.path)
                .context("Android model module has no evaluated directory provenance")?;
            ensure!(
                module.directory == *directory
                    && directory.is_absolute()
                    && directory.canonicalize()? == *directory,
                "Android model module {} does not match its evaluated canonical directory",
                module.path
            );
            if directory.starts_with(&root) {
                root.as_path()
            } else {
                directory.as_path()
            }
        } else {
            ensure!(
                module.directory.is_absolute()
                    && module.directory.canonicalize()?.starts_with(&root),
                "Module {} is outside the selected build; included builds and external project directories are unsupported",
                module.path
            );
            root.as_path()
        };
        if let Some(catalog) = &module.source_providers {
            let mut providers = BTreeSet::new();
            for provider in &catalog.providers {
                ensure!(
                    !provider.name.trim().is_empty()
                        && !provider.name.chars().any(char::is_control)
                        && providers.insert(&provider.name),
                    "Invalid or duplicate source provider in Android module {}",
                    module.path
                );
                for source in &provider.roots {
                    validate_project_path(&source.path, boundary)?;
                }
            }
        }
        let mut variants = BTreeSet::new();
        ensure!(
            module.default_variant.as_ref().is_none_or(|default| {
                module
                    .variants
                    .iter()
                    .any(|variant| &variant.name == default)
            }),
            "Default variant is absent from Android module {}",
            module.path
        );
        for variant in &module.variants {
            ensure!(
                valid_variant(&variant.name) && variants.insert(&variant.name),
                "Invalid or duplicate Android variant {}",
                variant.name
            );
            ensure!(
                variant
                    .components
                    .iter()
                    .filter(|component| component.scope == SourceScope::Main)
                    .count()
                    == 1,
                "Android variant {} must contain exactly one main component",
                variant.name
            );
            let mut components = BTreeSet::new();
            for component in &variant.components {
                ensure!(
                    valid_variant(&component.name) && components.insert(&component.name),
                    "Invalid or duplicate Android component {}",
                    component.name
                );
                for source in &component.sources {
                    validate_project_path(&source.path, boundary)?;
                }
                for dependency in &component.dependencies {
                    if let Dependency::Project { module, variant } = dependency {
                        ensure!(
                            model
                                .variant(&VariantId {
                                    module: module.clone(),
                                    variant: variant.clone()
                                })
                                .is_some(),
                            "Dependency {module}:{variant} is absent from the Android project model"
                        );
                    }
                }
            }
            if let Some(path) = &variant.output_listing {
                validate_project_path(path, boundary)?;
            }
        }
    }
    ensure!(
        model
            .modules
            .iter()
            .any(|module| module.kind != ModuleKind::Jvm),
        "No supported Android modules were found"
    );
    Ok(model)
}

fn validate_project_path(path: &Path, root: &Path) -> Result<()> {
    ensure!(
        path.is_absolute()
            && path.starts_with(root)
            && !path
                .components()
                .any(|part| matches!(part, PathComponent::ParentDir)),
        "Android model path is outside the selected project: {}",
        path.display()
    );
    // Generated roots may not exist until their producer has run. Resolve the nearest
    // existing ancestor so missing paths cannot bypass the symlink boundary check.
    let ancestor = path
        .ancestors()
        .find(|ancestor| ancestor.exists())
        .context("Android model path has no existing ancestor")?;
    ensure!(
        ancestor.canonicalize()?.starts_with(root),
        "Android model path escapes the project through a symlink: {}",
        path.display()
    );
    Ok(())
}

pub fn prepare() -> Result<tempfile::TempDir> {
    let directory = tempfile::Builder::new()
        .prefix("koda-android-model-")
        .tempdir()?;
    atomic_write(&directory.path().join("export.gradle"), EXPORT, false)?;
    Ok(directory)
}

fn selection_directory(root: &Path) -> Result<PathBuf> {
    ensure_directory(&root.join(".koda"))?;
    let cache = root.join(".koda/android-model");
    if cache.exists() {
        ensure_directory(&cache)?;
        ensure!(
            fs::read_to_string(cache.join(".gitignore"))? == MARKER,
            "The .koda/android-model directory contains unmanaged files; move it aside before syncing"
        );
    } else {
        ensure_directory(&cache)?;
        atomic_write(&cache.join(".gitignore"), MARKER, false)?;
    }
    Ok(cache)
}

pub fn install_selection(root: &Path, selected: &SelectedProject) -> Result<PathBuf> {
    ensure!(
        selected.model.root == root.canonicalize()?,
        "The Android selection belongs to a different project"
    );
    let cache = selection_directory(root)?;
    let path = cache.join("selected.json");
    atomic_write(
        &path,
        &serde_json::to_string(&selected.projection())?,
        false,
    )?;
    Ok(path)
}

