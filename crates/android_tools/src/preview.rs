    #[test]
    fn source_locations_disambiguate_packages_and_unsaved_overlays() -> Result<()> {
        let temporary = tempfile::tempdir()?;
        let root = temporary.path();
        let first = root.join("first");
        let second = root.join("second");
        fs::create_dir(&first)?;
        fs::create_dir(&second)?;
        let current = first.join("Main.kt");
        let other = second.join("Main.kt");
        fs::write(&current, "package first\n")?;
        fs::write(&other, "package second\n")?;
        let index = SourceIndex::new(
            root,
            &[current.clone(), other.clone()],
            &[(current.clone(), "package unsaved\n".into())],
            &["Main.kt".into()].into_iter().collect(),
        )?;
        let mut node = ComposeNode {
            name: "Text".into(),
            file_name: "Main.kt".into(),
            line_number: 4,
            package_hash: package_hash("second"),
            bounds: [0, 0, 100, 100],
            depth: 0,
            source_path: None,
        };
        assert_eq!(index.resolve(&node, &current), Some(other));
        node.package_hash = package_hash("unsaved");
        assert_eq!(index.resolve(&node, &current), Some(current.clone()));
        node.package_hash = package_hash("missing");
        assert!(index.resolve(&node, &current).is_none());
        node.source_path = Some(current);
        node.package_hash = package_hash("unsaved");
        let mut child = node.clone();
        child.bounds = [20, 20, 40, 40];
        child.depth = 2;
        child.line_number = 9;
        let mut framework = child.clone();
        framework.depth = 4;
        framework.source_path = None;
        let nodes = [node, child, framework];
        assert_eq!(hit_test(&nodes, 25., 25.), Some(1));
        assert_eq!(hit_test(&nodes, 50., 50.), Some(0));
        assert_eq!(hit_test(&nodes, 100., 50.), None);
        assert_eq!(hit_test(&nodes, f32::NAN, 50.), None);
        Ok(())
    }

